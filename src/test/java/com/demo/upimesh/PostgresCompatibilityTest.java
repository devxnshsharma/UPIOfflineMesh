package com.demo.upimesh;

import com.demo.upimesh.model.Account;
import com.demo.upimesh.model.IngestEvent;
import com.demo.upimesh.model.LedgerEntry;
import com.demo.upimesh.model.PacketRecord;
import org.hibernate.boot.Metadata;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.registry.StandardServiceRegistry;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.nio.file.Files;

import static org.junit.jupiter.api.Assertions.*;

/**
 * What can be proven about PostgreSQL without a PostgreSQL server: Hibernate generates the schema for the
 * PostgreSQL dialect and every idempotency guard is a plain UNIQUE constraint. The same suites that prove
 * exactly-once settlement on H2 can be run unchanged against a real server: see PostgresIngestionIT.
 */
class PostgresCompatibilityTest {

    private String ddl() throws Exception {
        File script = File.createTempFile("upimesh-pg-", ".sql");
        // Script-only schema generation through the standard JPA settings: no database connection is opened.
        StandardServiceRegistry registry = new StandardServiceRegistryBuilder()
                .applySetting("hibernate.dialect", "org.hibernate.dialect.PostgreSQLDialect")
                .applySetting("hibernate.boot.allow_jdbc_metadata_access", "false")
                .applySetting("jakarta.persistence.schema-generation.scripts.action", "create")
                .applySetting("jakarta.persistence.schema-generation.scripts.create-target", script.getPath())
                .build();
        try {
            Metadata metadata = new MetadataSources(registry).addAnnotatedClass(Account.class).addAnnotatedClass(LedgerEntry.class)
                    .addAnnotatedClass(PacketRecord.class).addAnnotatedClass(IngestEvent.class).buildMetadata();
            metadata.buildSessionFactory().close();
            return Files.readString(script.toPath()).toLowerCase();
        } finally {
            StandardServiceRegistryBuilder.destroy(registry);
            script.delete();
        }
    }

    @Test
    void theSchemaGeneratesForPostgreSqlWithMoneyAsExactNumerics() throws Exception {
        String ddl = ddl();
        for (String table : new String[]{"accounts", "ledger_entries", "packet_records", "ingest_events"}) {
            assertTrue(ddl.contains("create table " + table), table + " missing in:\n" + ddl);
        }
        assertTrue(ddl.contains("balance numeric(19,2)") && ddl.contains("amount numeric(19,2)"), "money must be exact numerics");
        assertFalse(ddl.contains("double") || ddl.contains("float"), "no floating point column anywhere");
        assertTrue(ddl.contains("version bigint"), "optimistic locking column");
        assertTrue(ddl.contains("bigint generated by default as identity"), "identity keys use native PostgreSQL syntax");
    }

    @Test
    void everyExactlyOnceGuardIsAUniqueConstraintThePostgreSqlEnforces() throws Exception {
        String ddl = ddl();
        assertTrue(ddl.contains("uk_ledger_nonce unique (nonce)"), "the same payment cannot settle twice, even repackaged");
        assertTrue(ddl.contains("uk_ledger_packet_hash unique (packet_hash)"), "the same bytes cannot settle twice");
        assertTrue(ddl.contains("uk_packet_records_hash unique (packet_hash)"), "the idempotency claim");
        assertTrue(ddl.contains("foreign key (sender_vpa) references accounts") && ddl.contains("foreign key (receiver_vpa) references accounts"));
    }
}
